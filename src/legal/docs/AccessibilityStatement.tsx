import { LEGAL, SOCIALS } from '../../data/site'
import { ContactDetails, ExternalLink, LegalLayout } from '../LegalLayout'

const social = (key: string) => SOCIALS.find((s) => s.key === key)!.href

/**
 * Accessibility statement (Israeli Equal Rights for Persons with Disabilities regulations, reg. 35).
 * Keep the "what we did" list honest – it describes features that exist on the site.
 */
export function AccessibilityStatement() {
  return (
    <LegalLayout id="accessibility" title="הצהרת נגישות">
      <p>
        אנו רואים חשיבות רבה במתן שירות שוויוני ונגיש לכל הגולשים, לרבות אנשים עם מוגבלות, ופועלים כדי שהאתר יהיה נוח
        וזמין לשימוש עבור כולם. פעלנו להתאים את האתר לתקנות שוויון זכויות לאנשים עם מוגבלות (התאמות נגישות לשירות),
        התשע״ג-2013, ולתקן הישראלי ת״י 5568, המבוסס על הנחיות WCAG 2.0, ברמה AA – ככל שהדבר אפשרי.
      </p>

      <h2>מה עשינו באתר</h2>
      <ul>
        <li>מבנה סמנטי עם כותרות מסודרות, התומך בקוראי מסך</li>
        <li>ניווט מלא באמצעות המקלדת, עם סימון ברור של הרכיב הפעיל וקישור ״דילוג לתוכן הראשי״</li>
        <li>טקסט חלופי לתמונות ותוויות לכפתורים ולרכיבים אינטראקטיביים</li>
        <li>ניגודיות גבוהה בין הטקסט לרקע</li>
        <li>התאמה מלאה למכשירים ניידים ולהגדלת התצוגה בדפדפן</li>
        <li>טפסים עם תוויות ברורות, הודעות שגיאה ומעבר אוטומטי לשדה שדורש תיקון</li>
        <li>כפתור להשהיית סרטון הרקע שבראש העמוד</li>
        <li>תמיכה בהגדרת ״הפחתת תנועה״ של מערכת ההפעלה: סרטון הרקע מוחלף בתמונה והאנימציות מנוטרלות</li>
      </ul>

      <h2>תפריט הנגישות</h2>
      <p>
        בכל עמוד באתר מופיע כפתור נגישות בפינה התחתונה של המסך. הכפתור פותח תפריט עם האפשרויות: הגדלה והקטנה של הטקסט,
        ניגודיות גבוהה, גווני אפור, הדגשת קישורים, גופן קריא, ריווח טקסט, עצירת אנימציות וסמן עכבר גדול. ההגדרות נשמרות
        בדפדפן לביקורים הבאים, וניתן לאפס אותן בלחיצה אחת.
      </p>

      <h2>מגבלות נגישות ידועות</h2>
      <ul>
        <li>
          נגני SoundCloud והפוסטים מאינסטגרם מוטמעים משירותים חיצוניים ואינם בשליטתנו המלאה, וייתכן שחלקם אינם נגישים
          במלואם. ניתן להאזין ולצפות בתכנים גם ישירות בעמודים שלנו ב
          <ExternalLink href={social('soundcloud')}>SoundCloud</ExternalLink> וב
          <ExternalLink href={social('instagram')}>אינסטגרם</ExternalLink>.
        </li>
        <li>סרטון הרקע שבראש העמוד הוא דקורטיבי, ללא קול וללא מידע מהותי.</li>
        <li>סרטונים ותמונות מאירועים אינם כוללים תמיד כתוביות או תיאור מילולי מלא.</li>
        <li>
          למרות מאמצינו, ייתכן שיתגלו באתר רכיבים שטרם הונגשו במלואם. אנו ממשיכים לשפר את נגישות האתר באופן שוטף.
        </li>
      </ul>

      <h2>נגישות השירות</h2>
      <p>
        השירות ניתן באירועים, במקום שבחרו הלקוחות, ואין לנו משרד או סניף לקבלת קהל. נשמח לתאם מראש כל התאמה הנדרשת לכם
        לשירות – פשוט דברו איתנו.
      </p>

      <h2>נתקלתם בבעיה? דברו איתנו</h2>
      <p>
        אם נתקלתם בקושי בגלישה או בבעיית נגישות כלשהי, נשמח שתעדכנו אותנו ונפעל לתקן אותה בהקדם. כדי שנוכל לטפל בפנייה,
        אנא ציינו את תיאור הבעיה, העמוד שבו נתקלתם בה ואת הדפדפן או הטכנולוגיה המסייעת שבה השתמשתם.
      </p>
      <p>
        <strong>רכז הנגישות:</strong> {LEGAL.accessibilityContact}
      </p>
      <ContactDetails />

      <h2>עדכון ההצהרה</h2>
      <p>הצהרת נגישות זו עודכנה ב-{LEGAL.updated}.</p>
    </LegalLayout>
  )
}
